package com.smartride.backend.driver.config;

import org.springframework.boot.CommandLineRunner;
import org.springframework.core.annotation.Order;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

@Component
@Order(-15)
public class DriverTripSchemaInitializer implements CommandLineRunner {
    private final JdbcTemplate jdbc;

    public DriverTripSchemaInitializer(JdbcTemplate jdbc) {
        this.jdbc = jdbc;
    }

    @Override
    public void run(String... args) {
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS driver_trip_assignments (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    booking_id BIGINT NOT NULL UNIQUE REFERENCES bookings(id) ON DELETE CASCADE,
                    driver_id BIGINT NOT NULL REFERENCES users(id),
                    fleet_manager_id BIGINT NOT NULL REFERENCES users(id),
                    assigned_by BIGINT NOT NULL REFERENCES users(id),
                    status VARCHAR(24) NOT NULL DEFAULT 'PENDING',
                    assigned_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    responded_at TIMESTAMP,
                    completed_at TIMESTAMP,
                    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """);
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_driver_trip_driver_status ON driver_trip_assignments(driver_id, status)");
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_driver_trip_manager_status ON driver_trip_assignments(fleet_manager_id, status)");
    }
}
