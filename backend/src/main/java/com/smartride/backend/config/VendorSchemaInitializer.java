package com.smartride.backend.config;

import org.springframework.boot.CommandLineRunner;
import org.springframework.core.annotation.Order;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

@Component
@Order(-30)
public class VendorSchemaInitializer implements CommandLineRunner {
    private final JdbcTemplate jdbc;

    public VendorSchemaInitializer(JdbcTemplate jdbc) {
        this.jdbc = jdbc;
    }

    @Override
    public void run(String... args) {
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS vendor_id BIGINT");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS subcategory VARCHAR(100)");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS \"year\" INTEGER");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS registration_number VARCHAR(50)");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS color VARCHAR(50)");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS fuel_type VARCHAR(50)");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS transmission VARCHAR(50)");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS seating_capacity INTEGER");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS mileage NUMERIC(8,2)");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS features VARCHAR(2000)");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS hourly_rate NUMERIC(10,2)");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS security_deposit NUMERIC(10,2)");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS km_limit_per_day INTEGER");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS extra_km_charge NUMERIC(10,2)");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS with_driver_rate NUMERIC(10,2)");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS description TEXT");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP");
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS vehicle_media (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    vehicle_id BIGINT NOT NULL REFERENCES vehicles(id) ON DELETE CASCADE,
                    media_type VARCHAR(30) NOT NULL,
                    storage_key VARCHAR(80) NOT NULL UNIQUE,
                    original_name VARCHAR(255) NOT NULL,
                    content_type VARCHAR(100) NOT NULL,
                    uploaded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS vendor_applications (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    application_number VARCHAR(40) NOT NULL UNIQUE,
                    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
                    business_name VARCHAR(255) NOT NULL,
                    business_type VARCHAR(100) NOT NULL,
                    business_email VARCHAR(255) NOT NULL,
                    business_mobile VARCHAR(30) NOT NULL,
                    business_address VARCHAR(1000) NOT NULL,
                    city VARCHAR(100) NOT NULL,
                    state VARCHAR(100) NOT NULL,
                    pincode VARCHAR(12) NOT NULL,
                    registration_number VARCHAR(100),
                    status VARCHAR(30) NOT NULL,
                    rejection_reason VARCHAR(1000),
                    submitted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    reviewed_at TIMESTAMP,
                    reviewed_by BIGINT REFERENCES users(id)
                )
                """);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS vendor_documents (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    application_id BIGINT NOT NULL REFERENCES vendor_applications(id) ON DELETE CASCADE,
                    document_type VARCHAR(40) NOT NULL,
                    storage_key VARCHAR(80) NOT NULL UNIQUE,
                    original_name VARCHAR(255) NOT NULL,
                    content_type VARCHAR(100) NOT NULL,
                    uploaded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS vendor_notifications (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                    title VARCHAR(160) NOT NULL,
                    message VARCHAR(1000) NOT NULL,
                    is_read BOOLEAN NOT NULL DEFAULT FALSE,
                    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """);
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_vendor_applications_status_date ON vendor_applications(status, submitted_at)");
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_vendor_documents_application ON vendor_documents(application_id)");
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_vehicle_media_vehicle_type ON vehicle_media(vehicle_id, media_type)");
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_vendor_notifications_user ON vendor_notifications(user_id, created_at)");
        jdbc.execute("ALTER TABLE bookings ADD COLUMN IF NOT EXISTS vendor_rejection_reason VARCHAR(1000)");
    }
}
