package com.smartride.backend.config;

import org.springframework.boot.CommandLineRunner;
import org.springframework.core.annotation.Order;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

@Component
@Order(-30)
public class VendorSchemaInitializer implements CommandLineRunner {
    private final JdbcTemplate jdbc;

    public VendorSchemaInitializer(JdbcTemplate jdbc) {
        this.jdbc = jdbc;
    }

    @Override
    public void run(String... args) {
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS vendor_applications (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    application_number VARCHAR(40) NOT NULL UNIQUE,
                    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
                    business_name VARCHAR(255) NOT NULL,
                    business_type VARCHAR(100) NOT NULL,
                    business_email VARCHAR(255) NOT NULL,
                    business_mobile VARCHAR(30) NOT NULL,
                    business_address VARCHAR(1000) NOT NULL,
                    city VARCHAR(100) NOT NULL,
                    state VARCHAR(100) NOT NULL,
                    pincode VARCHAR(12) NOT NULL,
                    registration_number VARCHAR(100),
                    status VARCHAR(30) NOT NULL,
                    rejection_reason VARCHAR(1000),
                    submitted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    reviewed_at TIMESTAMP,
                    reviewed_by BIGINT REFERENCES users(id)
                )
                """);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS vendor_documents (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    application_id BIGINT NOT NULL REFERENCES vendor_applications(id) ON DELETE CASCADE,
                    document_type VARCHAR(40) NOT NULL,
                    storage_key VARCHAR(80) NOT NULL UNIQUE,
                    original_name VARCHAR(255) NOT NULL,
                    content_type VARCHAR(100) NOT NULL,
                    uploaded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS vendor_notifications (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                    title VARCHAR(160) NOT NULL,
                    message VARCHAR(1000) NOT NULL,
                    is_read BOOLEAN NOT NULL DEFAULT FALSE,
                    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """);
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_vendor_applications_status_date ON vendor_applications(status, submitted_at)");
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_vendor_documents_application ON vendor_documents(application_id)");
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_vendor_notifications_user ON vendor_notifications(user_id, created_at)");
    }
}
