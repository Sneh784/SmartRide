package com.smartride.backend.config;

import org.springframework.boot.CommandLineRunner;
import org.springframework.core.annotation.Order;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

import java.util.List;

@Component
@Order(-30)
public class VendorSchemaInitializer implements CommandLineRunner {
    private static final List<String> VEHICLE_CATEGORIES = List.of(
            "Two-Wheelers", "Cars", "Commercial Vehicles", "Passenger Vehicles",
            "Construction Equipment", "Agricultural Machinery", "Watercraft",
            "Adventure Vehicles", "Emergency Vehicles");
    private final JdbcTemplate jdbc;

    public VendorSchemaInitializer(JdbcTemplate jdbc) {
        this.jdbc = jdbc;
    }

    @Override
    public void run(String... args) {
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS vendor_id BIGINT");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS category_id BIGINT");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS category VARCHAR(100)");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS subcategory VARCHAR(100)");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS name VARCHAR(255) NOT NULL DEFAULT 'Vehicle'");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS title VARCHAR(255) NOT NULL DEFAULT 'Vehicle'");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS brand VARCHAR(100)");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS model VARCHAR(100)");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS \"year\" INTEGER");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS registration_number VARCHAR(50)");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS color VARCHAR(50)");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS fuel_type VARCHAR(50)");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS transmission VARCHAR(50)");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS seating_capacity INTEGER");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS mileage NUMERIC(8,2)");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS features VARCHAR(2000)");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS daily_rental_price NUMERIC(10,2)");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS daily_rate NUMERIC(10,2)");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS hourly_rental_price NUMERIC(10,2)");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS hourly_rate NUMERIC(10,2)");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS security_deposit NUMERIC(10,2)");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS km_limit_per_day INTEGER");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS extra_km_charge NUMERIC(10,2)");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS with_driver_rate NUMERIC(10,2)");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS driver_charge_daily NUMERIC(10,2)");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS with_driver_available BOOLEAN DEFAULT TRUE");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS without_driver_available BOOLEAN DEFAULT TRUE");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS pickup_location VARCHAR(200)");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS city VARCHAR(100)");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS location VARCHAR(200)");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS availability_status VARCHAR(50) DEFAULT 'UNAVAILABLE'");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS approval_status VARCHAR(50) DEFAULT 'PENDING'");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS approval_reason VARCHAR(1000)");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS description TEXT");
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP");
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS vehicle_categories (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name VARCHAR(100) NOT NULL UNIQUE,
                    description TEXT,
                    icon_url VARCHAR(500),
                    display_order INTEGER,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
                """);
        for (int index = 0; index < VEHICLE_CATEGORIES.size(); index++) {
            String category = VEHICLE_CATEGORIES.get(index);
            jdbc.update("""
                    INSERT INTO vehicle_categories (name, display_order)
                    SELECT ?, ? WHERE NOT EXISTS (
                        SELECT 1 FROM vehicle_categories WHERE LOWER(name) = LOWER(?)
                    )
                    """, category, index + 1, category);
        }
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS vehicle_media (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    vehicle_id BIGINT NOT NULL REFERENCES vehicles(id) ON DELETE CASCADE,
                    media_type VARCHAR(30) NOT NULL,
                    storage_key VARCHAR(80) NOT NULL UNIQUE,
                    original_name VARCHAR(255) NOT NULL,
                    content_type VARCHAR(100) NOT NULL,
                    uploaded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS vendor_applications (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    application_number VARCHAR(40) NOT NULL UNIQUE,
                    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
                    business_name VARCHAR(255) NOT NULL,
                    business_type VARCHAR(100) NOT NULL,
                    business_email VARCHAR(255) NOT NULL,
                    business_mobile VARCHAR(30) NOT NULL,
                    business_address VARCHAR(1000) NOT NULL,
                    city VARCHAR(100) NOT NULL,
                    state VARCHAR(100) NOT NULL,
                    pincode VARCHAR(12) NOT NULL,
                    registration_number VARCHAR(100),
                    status VARCHAR(30) NOT NULL,
                    rejection_reason VARCHAR(1000),
                    submitted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    reviewed_at TIMESTAMP,
                    reviewed_by BIGINT REFERENCES users(id)
                )
                """);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS vendor_profiles (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
                    business_name VARCHAR(255) NOT NULL,
                    business_type VARCHAR(100),
                    business_email VARCHAR(255),
                    business_phone VARCHAR(30),
                    address TEXT NOT NULL,
                    city VARCHAR(100) NOT NULL,
                    state VARCHAR(100) NOT NULL,
                    pin_code VARCHAR(12) NOT NULL,
                    total_vehicles INTEGER DEFAULT 0,
                    total_earnings NUMERIC(12,2) DEFAULT 0,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
                """);
        jdbc.update("""
                INSERT INTO vendor_profiles (
                    user_id, business_name, business_type, business_email, business_phone,
                    address, city, state, pin_code
                )
                SELECT va.user_id, va.business_name, va.business_type, va.business_email,
                       va.business_mobile, va.business_address, va.city, va.state, va.pincode
                FROM vendor_applications va
                WHERE UPPER(va.status) = 'APPROVED'
                  AND NOT EXISTS (
                      SELECT 1 FROM vendor_profiles vp WHERE vp.user_id = va.user_id
                  )
                """);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS vendor_documents (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    application_id BIGINT NOT NULL REFERENCES vendor_applications(id) ON DELETE CASCADE,
                    document_type VARCHAR(40) NOT NULL,
                    storage_key VARCHAR(80) NOT NULL UNIQUE,
                    original_name VARCHAR(255) NOT NULL,
                    content_type VARCHAR(100) NOT NULL,
                    uploaded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS vendor_notifications (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                    title VARCHAR(160) NOT NULL,
                    message VARCHAR(1000) NOT NULL,
                    is_read BOOLEAN NOT NULL DEFAULT FALSE,
                    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """);
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_vendor_applications_status_date ON vendor_applications(status, submitted_at)");
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_vendor_documents_application ON vendor_documents(application_id)");
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_vehicle_media_vehicle_type ON vehicle_media(vehicle_id, media_type)");
        jdbc.execute("ALTER TABLE vehicle_media ADD COLUMN IF NOT EXISTS cloudinary_public_id VARCHAR(255)");
        jdbc.execute("ALTER TABLE vehicle_media ADD COLUMN IF NOT EXISTS secure_url VARCHAR(1000)");
        jdbc.execute("ALTER TABLE vehicle_media ALTER COLUMN storage_key TYPE VARCHAR(255)");
        jdbc.execute("ALTER TABLE vendor_documents ADD COLUMN IF NOT EXISTS cloudinary_public_id VARCHAR(255)");
        jdbc.execute("ALTER TABLE vendor_documents ADD COLUMN IF NOT EXISTS secure_url VARCHAR(1000)");
        jdbc.execute("ALTER TABLE vendor_documents ALTER COLUMN storage_key TYPE VARCHAR(255)");
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_vendor_notifications_user ON vendor_notifications(user_id, created_at)");
        jdbc.execute("ALTER TABLE bookings ADD COLUMN IF NOT EXISTS vendor_rejection_reason VARCHAR(1000)");
    }
}
