package com.smartride.backend.config;

import org.springframework.boot.CommandLineRunner;
import org.springframework.core.annotation.Order;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

@Component
@Order(-20)
public class FleetManagerSchemaInitializer implements CommandLineRunner {
    private final JdbcTemplate jdbc;

    public FleetManagerSchemaInitializer(JdbcTemplate jdbc) {
        this.jdbc = jdbc;
    }

    @Override
    public void run(String... args) {
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS fleet_manager_vehicle_access (
                    fleet_manager_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                    vehicle_id BIGINT NOT NULL REFERENCES vehicles(id) ON DELETE CASCADE,
                    granted_by BIGINT REFERENCES users(id),
                    granted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    PRIMARY KEY (fleet_manager_id, vehicle_id)
                )
                """);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS fleet_manager_driver_access (
                    fleet_manager_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                    driver_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                    granted_by BIGINT REFERENCES users(id),
                    granted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    PRIMARY KEY (fleet_manager_id, driver_id)
                )
                """);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS fleet_vehicle_assignments (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    fleet_manager_id BIGINT NOT NULL REFERENCES users(id),
                    vehicle_id BIGINT NOT NULL REFERENCES vehicles(id),
                    driver_id BIGINT NOT NULL REFERENCES users(id),
                    start_at TIMESTAMP NOT NULL,
                    end_at TIMESTAMP,
                    location VARCHAR(200) NOT NULL,
                    purpose VARCHAR(300) NOT NULL,
                    notes VARCHAR(2000),
                    status VARCHAR(24) NOT NULL DEFAULT 'ASSIGNED',
                    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    CHECK (end_at IS NULL OR end_at > start_at)
                )
                """);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS fleet_maintenance_records (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    fleet_manager_id BIGINT NOT NULL REFERENCES users(id),
                    vehicle_id BIGINT NOT NULL REFERENCES vehicles(id),
                    maintenance_type VARCHAR(80) NOT NULL,
                    description VARCHAR(2000) NOT NULL,
                    scheduled_at TIMESTAMP NOT NULL,
                    completed_at TIMESTAMP,
                    service_provider VARCHAR(255),
                    estimated_cost NUMERIC(12,2),
                    actual_cost NUMERIC(12,2),
                    priority VARCHAR(20) NOT NULL DEFAULT 'MEDIUM',
                    status VARCHAR(24) NOT NULL DEFAULT 'SCHEDULED',
                    notes VARCHAR(2000),
                    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS fleet_maintenance_requests (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    fleet_manager_id BIGINT NOT NULL REFERENCES users(id),
                    vehicle_id BIGINT NOT NULL REFERENCES vehicles(id),
                    reported_by BIGINT NOT NULL REFERENCES users(id),
                    description VARCHAR(2000) NOT NULL,
                    priority VARCHAR(20) NOT NULL DEFAULT 'MEDIUM',
                    status VARCHAR(24) NOT NULL DEFAULT 'OPEN',
                    notes VARCHAR(2000),
                    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS fleet_manager_notifications (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                    notification_type VARCHAR(40) NOT NULL,
                    title VARCHAR(160) NOT NULL,
                    message VARCHAR(1000) NOT NULL,
                    is_read BOOLEAN NOT NULL DEFAULT FALSE,
                    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS fleet_manager_preferences (
                    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
                    email_notifications BOOLEAN NOT NULL DEFAULT TRUE,
                    compact_tables BOOLEAN NOT NULL DEFAULT FALSE,
                    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """);
        jdbc.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS operational_status VARCHAR(30) NOT NULL DEFAULT 'AVAILABLE'");
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_fm_vehicle_access_vehicle ON fleet_manager_vehicle_access(vehicle_id)");
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_fm_driver_access_driver ON fleet_manager_driver_access(driver_id)");
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_fleet_assignments_vehicle_dates ON fleet_vehicle_assignments(vehicle_id, start_at, end_at)");
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_fleet_assignments_driver_dates ON fleet_vehicle_assignments(driver_id, start_at, end_at)");
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_fleet_maintenance_vehicle_status ON fleet_maintenance_records(vehicle_id, status, scheduled_at)");
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_fleet_notifications_user_read ON fleet_manager_notifications(user_id, is_read, created_at)");
    }
}
