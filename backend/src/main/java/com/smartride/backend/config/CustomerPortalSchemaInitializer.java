package com.smartride.backend.config;

import org.springframework.boot.CommandLineRunner;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;
import org.springframework.core.annotation.Order;

@Component
@Order(-50)
public class CustomerPortalSchemaInitializer implements CommandLineRunner {
    private final JdbcTemplate jdbcTemplate;

    public CustomerPortalSchemaInitializer(JdbcTemplate jdbcTemplate) {
        this.jdbcTemplate = jdbcTemplate;
    }

    @Override
    public void run(String... args) {
        jdbcTemplate.execute("""
                CREATE TABLE IF NOT EXISTS vehicles (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    title VARCHAR(255) NOT NULL DEFAULT 'Vehicle',
                    brand VARCHAR(100), model VARCHAR(100), category VARCHAR(100),
                    city VARCHAR(100), location VARCHAR(200), daily_rate NUMERIC(10,2),
                    rating NUMERIC(3,2) DEFAULT 0, availability_status VARCHAR(50)
                )
                """);
        jdbcTemplate.execute("""
                CREATE TABLE IF NOT EXISTS bookings (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    customer_id BIGINT REFERENCES users(id),
                    vehicle_id BIGINT REFERENCES vehicles(id),
                    booking_type VARCHAR(50),
                    pickup_date TIMESTAMP NOT NULL,
                    return_date TIMESTAMP NOT NULL,
                    pickup_location VARCHAR(200),
                    return_location VARCHAR(200),
                    status VARCHAR(50) DEFAULT 'PENDING',
                    amount NUMERIC(10,2),
                    payment_status VARCHAR(50) DEFAULT 'PENDING',
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
                """);
        jdbcTemplate.execute("""
                CREATE TABLE IF NOT EXISTS payments (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    booking_id BIGINT REFERENCES bookings(id),
                    amount NUMERIC(10,2) NOT NULL,
                    currency VARCHAR(10) DEFAULT 'INR',
                    provider VARCHAR(50),
                    payment_id VARCHAR(200),
                    status VARCHAR(50) DEFAULT 'PENDING',
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
                """);
        jdbcTemplate.execute("""
                CREATE TABLE IF NOT EXISTS customer_wishlist (
                    customer_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                    vehicle_id BIGINT NOT NULL REFERENCES vehicles(id) ON DELETE CASCADE,
                    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    PRIMARY KEY (customer_id, vehicle_id)
                )
                """);
        jdbcTemplate.execute("""
                CREATE TABLE IF NOT EXISTS customer_kyc (
                    customer_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
                    document_type VARCHAR(40) NOT NULL,
                    document_last_four VARCHAR(4) NOT NULL,
                    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
                    submitted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """);
        jdbcTemplate.execute("""
                CREATE TABLE IF NOT EXISTS customer_notifications (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    customer_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                    title VARCHAR(160) NOT NULL,
                    message VARCHAR(1000) NOT NULL,
                    is_read BOOLEAN NOT NULL DEFAULT FALSE,
                    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """);
        jdbcTemplate.execute("""
                CREATE TABLE IF NOT EXISTS customer_support_tickets (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    customer_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                    subject VARCHAR(160) NOT NULL,
                    message VARCHAR(3000) NOT NULL,
                    status VARCHAR(20) NOT NULL DEFAULT 'OPEN',
                    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """);
    }
}
