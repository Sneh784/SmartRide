package com.smartride.backend.config;

import org.springframework.boot.CommandLineRunner;
import org.springframework.core.annotation.Order;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

@Component
@Order(-40)
public class AdminSchemaInitializer implements CommandLineRunner {
    private final JdbcTemplate jdbcTemplate;

    public AdminSchemaInitializer(JdbcTemplate jdbcTemplate) {
        this.jdbcTemplate = jdbcTemplate;
    }

    @Override
    public void run(String... args) {
        jdbcTemplate.execute("ALTER TABLE users ADD COLUMN IF NOT EXISTS approval_status VARCHAR(30)");
        jdbcTemplate.execute("ALTER TABLE users ADD COLUMN IF NOT EXISTS approval_reason VARCHAR(1000)");
        jdbcTemplate.execute("ALTER TABLE users ADD COLUMN IF NOT EXISTS approved_at TIMESTAMP");
        jdbcTemplate.execute("ALTER TABLE users ADD COLUMN IF NOT EXISTS approved_by BIGINT REFERENCES users(id)");
        jdbcTemplate.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS approval_status VARCHAR(30)");
        jdbcTemplate.execute("ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS approval_reason VARCHAR(1000)");
        jdbcTemplate.execute("ALTER TABLE customer_kyc ADD COLUMN IF NOT EXISTS rejection_reason VARCHAR(1000)");
        jdbcTemplate.execute("""
                CREATE TABLE IF NOT EXISTS approval_email_notifications (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT NOT NULL REFERENCES users(id),
                    account_type VARCHAR(20) NOT NULL,
                    recipient_email VARCHAR(320) NOT NULL,
                    recipient_name VARCHAR(200) NOT NULL,
                    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
                    attempt_count INTEGER NOT NULL DEFAULT 0,
                    last_attempt_at TIMESTAMP,
                    sent_at TIMESTAMP,
                    last_error VARCHAR(200),
                    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    CONSTRAINT uq_approval_email_user_type UNIQUE (user_id, account_type)
                )
                """);
        jdbcTemplate.execute("""
                CREATE TABLE IF NOT EXISTS admin_audit_log (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    admin_id BIGINT REFERENCES users(id),
                    action VARCHAR(80) NOT NULL,
                    entity_type VARCHAR(50) NOT NULL,
                    entity_id BIGINT,
                    reason VARCHAR(1000),
                    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """);
        jdbcTemplate.execute("""
                CREATE TABLE IF NOT EXISTS admin_notifications (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    title VARCHAR(160) NOT NULL,
                    message VARCHAR(1000) NOT NULL,
                    event_type VARCHAR(50) NOT NULL,
                    entity_type VARCHAR(50),
                    entity_id BIGINT,
                    is_read BOOLEAN NOT NULL DEFAULT FALSE,
                    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """);
        jdbcTemplate.execute("""
                CREATE TABLE IF NOT EXISTS platform_settings (
                    setting_key VARCHAR(100) PRIMARY KEY,
                    setting_value VARCHAR(2000) NOT NULL,
                    updated_by BIGINT REFERENCES users(id),
                    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """);
    }
}
